"""成员(0024)写入端点 —— 消费/收入成员，非共享账本协作者。

注意区分 `src/routers/members.py`(账本协作者/邀请管理,挂在 `/api/v1/ledgers/...`):
本文件是 user-global 的「成员名单」实体,跟 tags 同构,挂在
`/api/v1/write/ledgers/{ledger_id}/members`。
"""
from __future__ import annotations

from fastapi import APIRouter, Depends, Header, Request

from ._shared import *  # noqa: F401,F403 — 集中从 _shared 取所有 symbol

router = APIRouter()


@router.post(
    "/ledgers/{ledger_id}/members",
    response_model=WriteCommitMeta,
    responses=_WRITE_RESPONSES,
)
async def create_member_api(
    ledger_id: str,
    req: WriteMemberCreateRequest,
    request: Request,
    idempotency_key: str | None = Header(default=None, alias="Idempotency-Key"),
    device_id: str = Header(default="web-console", alias="X-Device-ID"),
    _scopes: set[str] = Depends(_WRITE_SCOPE_DEP),
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
) -> WriteCommitMeta:
    payload = req.model_dump(mode="json")
    ledger, replay = _prepare_write(
        db=db,
        current_user=current_user,
        ledger_external_id=ledger_id,
        required_roles=_OWNER_ONLY_ROLES,
        idempotency_key=idempotency_key,
        device_id=device_id,
        method=request.method,
        path=request.url.path,
        payload=payload,
    )
    if replay:
        return replay
    mutate_payload = _payload_with_actor(payload, current_user, ledger=ledger)
    return await _commit_write(
        request=request,
        db=db,
        current_user=current_user,
        ledger=ledger,
        base_change_id=req.base_change_id,
        request_payload=payload,
        idempotency_key=idempotency_key,
        device_id=device_id,
        audit_action="web_member_create",
        mutate=lambda snapshot: create_member(snapshot, mutate_payload),
    )


